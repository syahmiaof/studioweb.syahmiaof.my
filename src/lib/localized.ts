function chinese<T>(value: T): T {
  if (typeof value === "string") return (ZH_CONTENT[value] ?? value) as T;
  if (Array.isArray(value)) return value.map((item) => chinese(item)) as T;
  return value;
}

export function localized<T>(value: { ms: T; en: T; "zh-Hans"?: T }, locale: Locale): T {
  if (locale === "ms") return value.ms;
  if (locale === "zh-Hans") return value["zh-Hans"] ?? chinese(value.en);
  return value.en;
}

export function localizedPriceLabel(value: string, locale: Locale): string {
  const amount = value.match(/RM[\d,]+/)?.[0];
  if (!amount) return value;
  if (/^(Dari|From)/i.test(value)) return locale === "zh-Hans" ? `${amount} 起` : `From ${amount}`;
  if (/^(Lebih|Above|More than)/i.test(value)) return locale === "zh-Hans" ? `高于 ${amount}` : `Above ${amount}`;
  return value;
}
